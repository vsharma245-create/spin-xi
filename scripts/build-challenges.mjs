/**
 * Writes supabase/challenges.sql — the daily rotation, and nothing else.
 *
 * The rotation is the one part of the archive that changes for editorial
 * reasons rather than because new cricket has been played. Rebuilding the
 * whole archive to add an objective would recompute every rating and
 * re-derive every nationality, which is a great deal of risk for a line of
 * text, so this emits that table on its own.
 */
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { FORMAT_CYCLE, OBJECTIVES, PRESET_CYCLE, SLOTS } from './challenges.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const lit = (v) => `'${String(v).replace(/'/g, "''")}'`
const arr = (xs) => `array[${xs.map(lit).join(', ')}]`

/*
 * Emitted as the rule rather than as 546 rows of the rule's output.
 *
 * The rotation is three cycles read off the slot number, and writing it that
 * way keeps the SQL short enough to paste into a console and short enough to
 * check by eye — the arrays are the same three lists the game is built from,
 * and the modulo is the whole of the logic. Five hundred and forty-six
 * literal rows would say the same thing while hiding it.
 */
const sql = `-- SPIN XI — the daily rotation
-- Generated by scripts/build-challenges.mjs. Do not edit by hand.
--
--   ${SLOTS} slots · ${OBJECTIVES.length} objectives
--
-- Which challenge a given day gets is slot = days-since-epoch mod ${SLOTS}, so
-- everybody plays the same one without a calendar to keep topped up. The draw
-- itself — which squads you spin — is seeded on the day and differs every day
-- regardless, so this governs the shape of the puzzle, not its content.
--
-- ${SLOTS} is lcm(${FORMAT_CYCLE.length} formats, ${PRESET_CYCLE.length} presets, ${OBJECTIVES.length} objectives): the first day a pairing repeats.
--
-- Safe to run on its own, and safe to re-run. It replaces this one table and
-- touches nothing else, so no rating is recomputed and no nationality is
-- re-derived.

begin;

delete from challenges;

insert into challenges (slot, format, preset_id, objective, objective_desc, active)
select
  slot,
  (${arr(FORMAT_CYCLE)})[slot % ${FORMAT_CYCLE.length} + 1],
  (${arr(PRESET_CYCLE)})[slot % ${PRESET_CYCLE.length} + 1],
  (${arr(OBJECTIVES.map((o) => o[0]))})[slot % ${OBJECTIVES.length} + 1],
  (${arr(OBJECTIVES.map((o) => o[1]))})[slot % ${OBJECTIVES.length} + 1],
  true
from generate_series(0, ${SLOTS - 1}) as slot;

-- Any client holding a cached archive must fetch the new rotation.
update dataset_meta set version = gen_random_uuid(), updated_at = now();

commit;
`

await writeFile(join(ROOT, 'supabase/challenges.sql'), sql)
console.log(`  challenges.sql — ${SLOTS} slots, ${OBJECTIVES.length} objectives`)
